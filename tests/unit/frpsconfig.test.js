'use strict';
/* frps.toml 的解析 / 摘要 / 向导写入。
 * 这里是「改服务器配置」的唯一出口：写错就会把别人配好的 token、vhost 端口
 * 悄悄删掉，或者把 docker 的 dashboard 段（旧字段名）留下变成死配置。 */
const test = require('node:test');
const assert = require('node:assert/strict');
const frps = require('../../src/main/frpsconfig');

test('parseConfig：合法 TOML → ok，语法错误 → 中文提示', () => {
  const ok = frps.parseConfig('bindPort = 7000\n[auth]\ntoken = "abcdefghijk"\n');
  assert.equal(ok.ok, true);
  assert.equal(ok.data.bindPort, 7000);
  const bad = frps.parseConfig('bindPort = \n');
  assert.equal(bad.ok, false);
  assert.equal(typeof bad.error, 'string');
  assert.ok(bad.error.length > 0);
});

test('parseAllowPorts：范围 / 单端口 / 非法输入', () => {
  const ok = frps.parseAllowPorts('2000-3000, 3001 4000');
  assert.equal(ok.ok, true);
  assert.deepEqual(ok.value, [{ start: 2000, end: 3000 }, { single: 3001 }, { single: 4000 }]);
  assert.equal(frps.parseAllowPorts('').value, null);
  assert.equal(frps.parseAllowPorts('3000-2000').ok, false, '反序范围要报错');
  assert.equal(frps.parseAllowPorts('70000').ok, false);
  assert.equal(frps.parseAllowPorts('abc').ok, false);
});

test('allowPortsToText：与 parseAllowPorts 互为逆运算', () => {
  const parsed = frps.parseAllowPorts('2000-3000,3001');
  assert.equal(frps.allowPortsToText(parsed.value), '2000-3000,3001');
  assert.equal(frps.allowPortsToText(null), '');
});

test('summary：旧字段名 dashboard 也认，且可选端口缺省为 0', () => {
  const s = frps.summary({
    bindPort: 7000,
    auth: { token: 'tok' },
    dashboard: { port: 7500, user: 'admin', password: 'p' },
    vhostHTTPPort: 8080,
  });
  assert.equal(s.bindPort, 7000);
  assert.equal(s.authEnabled, true);
  assert.equal(s.token, 'tok');
  assert.equal(s.webEnabled, true);
  assert.equal(s.webPort, 7500);
  assert.equal(s.vhostHTTPPort, 8080);
  assert.equal(s.vhostHTTPSPort, 0);
  assert.equal(s.tcpmuxHTTPConnectPort, 0, '没配的可选端口必须是 0，不能当需要放行的端口');
});

test('summary：allowPortsText 回填成可读文本', () => {
  const s = frps.summary({ bindPort: 7000, allowPorts: [{ start: 2000, end: 3000 }, { single: 4000 }] });
  assert.equal(s.allowPortsText, '2000-3000,4000');
});

test('validateFields：端口范围、token 为空、Dashboard 与 bindPort 冲突', () => {
  assert.equal(frps.validateFields({ bindPort: 0 }).ok, false);
  const noToken = frps.validateFields({ bindPort: 7000, authEnabled: true, token: '' });
  assert.ok(noToken.errors.some((e) => /token/.test(e)));
  const clash = frps.validateFields({ bindPort: 7000, webEnabled: true, webPort: 7000, token: 'abcdefghijk' });
  assert.ok(clash.errors.some((e) => /不能与 bindPort 相同/.test(e)));
  const weak = frps.validateFields({ bindPort: 7000, token: 'short' });
  assert.equal(weak.ok, true);
  assert.ok(weak.warnings.some((w) => /少于 8/.test(w)));
});

test('applyWizard：未给出的字段从现有配置继承（不会悄悄删掉 token / vhost）', () => {
  const base = { bindPort: 7000, auth: { method: 'token', token: 'keepme123456' }, vhostHTTPPort: 8080 };
  const out = frps.applyWizard(base, { bindPort: 7001 });
  assert.equal(out.ok, true);
  assert.equal(out.data.bindPort, 7001);
  assert.equal(out.data.auth.token, 'keepme123456', 'token 必须保留');
  assert.equal(out.data.vhostHTTPPort, 8080, 'vhost 端口必须保留');
});

test('applyWizard：关掉鉴权 / 关掉 Dashboard 时对应段落被删除', () => {
  const base = { bindPort: 7000, auth: { token: 'x' }, webServer: { port: 4096, user: 'admin', password: 'p' }, dashboard: { port: 4096 } };
  const out = frps.applyWizard(base, { bindPort: 7000, authEnabled: false, webEnabled: false });
  assert.equal(out.ok, true);
  assert.equal(out.data.auth, undefined);
  assert.equal(out.data.webServer, undefined);
  assert.equal(out.data.dashboard, undefined, '旧字段名也要清掉');
});

test('applyWizard：校验失败时不产出文本', () => {
  const out = frps.applyWizard({}, { bindPort: 7000, authEnabled: true, token: '' });
  assert.equal(out.ok, false);
  assert.equal(out.text, undefined);
  assert.ok(Array.isArray(out.errors) && out.errors.length > 0);
});

test('applyWizard：生成的文本能被 parseConfig 解析回来（自洽）', () => {
  const out = frps.applyWizard({}, { bindPort: 7123, authEnabled: true, token: 'abcdefghijk', webEnabled: true, webPort: 4096, webUser: 'admin', webPassword: 'pwd' }, { includeMeta: true });
  assert.equal(out.ok, true);
  assert.match(out.text, /generated by FRP 控制台/);
  const parsed = frps.parseConfig(out.text);
  assert.equal(parsed.ok, true);
  assert.equal(parsed.data.bindPort, 7123);
  assert.equal(parsed.data.auth.token, 'abcdefghijk');
});
